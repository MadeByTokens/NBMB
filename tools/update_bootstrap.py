#!/usr/bin/env python3
"""Refresh data.js from the IANA RDAP list and rebuild the CSP in index.html.

The CSP allows only https RDAP hosts, so the page cannot send data elsewhere.
Run this now and then; the page itself never contacts IANA.
"""
import json
import pathlib
import re
import socket
import urllib.parse
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = "https://data.iana.org/rdap/dns.json"
HOST = re.compile(r"^[a-z0-9.-]+(:[0-9]+)?$")
MIN_SERVICES = 400  # far fewer means a damaged list, which must not reach the page
CSP_BLOCK = re.compile(r"<!-- csp:start -->.*?<!-- csp:end -->", re.S)
OVERRIDE_HOSTS = {"rdap.identitydigital.services"}  # SERVER_OVERRIDES in lib.js


def godaddy_hosts(hosts):
    """GoDaddy serves many rdap.nic.* names, visible only through their DNS aliases."""
    found = []
    for host in sorted(hosts):
        try:
            canonical, aliases, _ = socket.gethostbyname_ex(host)
        except OSError:
            continue
        if any(".godaddy" in name for name in [canonical, *aliases]):
            found.append(host)
    if not found:
        raise SystemExit("no GoDaddy hosts found; is DNS working?")
    return found


def main():
    with urllib.request.urlopen(SOURCE, timeout=30) as response:
        data = json.load(response)

    services = []
    hosts = set()
    for tlds, urls in data["services"]:
        https = [u for u in urls if u.startswith("https://")]
        if not https:
            continue
        host = urllib.parse.urlsplit(https[0]).netloc.lower()
        if not HOST.match(host):
            raise SystemExit(f"refusing odd host: {host!r}")
        hosts.add(host)
        services.append([tlds, https[:1]])

    if len(services) < MIN_SERVICES:
        raise SystemExit(f"refusing a list with only {len(services)} services")

    hosts |= OVERRIDE_HOSTS
    hosts.add("dns.google")  # the opt-in DNS check; see lib.js
    connect = " ".join(f"https://{h}" for h in sorted(hosts))
    policy = (
        "default-src 'none'; script-src 'self'; style-src 'self'; img-src 'self' data:; font-src 'self'; "
        f"base-uri 'none'; form-action 'none'; connect-src {connect}"
    )
    block = (
        "<!-- csp:start -->\n"
        f'<meta http-equiv="Content-Security-Policy" content="{policy}">\n'
        "<!-- csp:end -->"
    )
    page = ROOT / "index.html"
    html, replaced = CSP_BLOCK.subn(lambda _: block, page.read_text())
    if replaced != 1:
        raise SystemExit(f"expected one CSP block in index.html, found {replaced}")
    page.write_text(html)

    bootstrap = {
        "publication": data["publication"],
        "godaddyHosts": godaddy_hosts(hosts),
        "services": services,
    }
    (ROOT / "data.js").write_text(
        "// Generated by tools/update_bootstrap.py. Do not edit.\n"
        f"export const BOOTSTRAP = {json.dumps(bootstrap, separators=(',', ':'))};\n"
    )
    print(f"{len(services)} services, {len(hosts)} hosts, published {data['publication']}")


if __name__ == "__main__":
    main()
